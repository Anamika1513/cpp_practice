#include <iostream>
using namespace std;

int main(){
    int x = 4;
    cout<<x<<endl;

    // post increament
    x++;
    cout<<x<<endl;
    x=x+1;
    cout<<x<<endl;
    x += 1;
    cout<<x<<endl;

    // post decreament
    x--;
    cout<<x<<endl;
    x=x-1;
    cout<<x<<endl;
    x -= 1;
    cout<<x<<endl;

    // pree decreament
    --x;
    cout<<x<<endl;

    // post increament
    ++x;
    cout<<x<<endl;
    
}
